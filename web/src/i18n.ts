const tables: Record<Lang, typeof en> = { en, zh };

export function makeT(lang: Lang): typeof en {
  return tables[lang];
}

/** Catalog-currency money, per-locale shape (zh ¥; en CNY x.xx). */
export function money(lang: Lang, micros: number): string {
  const v = micros / 1e6;
  return lang === "zh" ? `¥${v.toFixed(v >= 1 ? 2 : 4)}` : `CNY ${v.toFixed(v >= 1 ? 2 : 4)}`;
}

/** Per-locale short time (HH:MM). */
export function timeStr(lang: Lang, iso: string): string {
  const d = new Date(iso);
  return d.toLocaleTimeString(lang === "zh" ? "zh-CN" : "en-GB", { hour: "2-digit", minute: "2-digit" });
}

/** Elapsed mm:ss / Xm. */
export function elapsed(ms: number): string {
  const s = Math.max(0, Math.round(ms / 1000));
  return s < 60 ? `${s}s` : `${Math.floor(s / 60)}m${String(s % 60).padStart(2, "0")}s`;
}
